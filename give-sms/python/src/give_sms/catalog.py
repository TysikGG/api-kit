def find_country(value: str | int) -> tuple[str, CountryInfo] | None:
    """Resolve a country slug or handler id to the catalog entry, if known."""
    text = str(value).strip().lower()
    if text in COUNTRIES:
        return text, COUNTRIES[text]
    if text.isdigit() or (text.startswith("-") and text[1:].isdigit()):
        handler_id = int(text)
        for code, info in COUNTRIES.items():
            if info["handler_id"] == handler_id:
                return code, info
    return None
