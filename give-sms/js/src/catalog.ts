export type ServiceCode = keyof typeof SERVICES;

/** Resolve a country slug or handler id to the catalog entry, if known. */
export function findCountry(value: string | number): { code: string; info: CountryInfo } | undefined {
  const text = String(value).trim().toLowerCase();
  if (Object.prototype.hasOwnProperty.call(COUNTRIES, text)) {
    return { code: text, info: COUNTRIES[text as CountryCode] };
  }
  const id = Number(text);
  if (!Number.isNaN(id) && text !== "") {
    for (const [code, info] of Object.entries(COUNTRIES)) {
      if (info.handlerId === id) {
        return { code, info };
      }
    }
  }
  return undefined;
}
